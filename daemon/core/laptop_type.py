"""Laptop type detection and kernel module parameter management."""

import os
import re
import logging
from enum import Enum
from typing import Optional

log = logging.getLogger("acersense.laptop_type")

CONFIG_DIR = "/etc/acersense"
MODPROBE_CONF = "/etc/modprobe.d/linuwu-sense.conf"
RESTART_FILE = os.path.join(CONFIG_DIR, "driver_restart_count")
MAX_RESTART_ATTEMPTS = 20


class LaptopType(Enum):
    UNKNOWN = "UNKNOWN"
    NITRO = "NITRO"
    PREDATOR = "PREDATOR"


def detect_current_modprobe_param(conf_path: str = MODPROBE_CONF) -> str:
    """Read forced model quirk parameter from modprobe configuration."""
    if not os.path.exists(conf_path):
        return ""
    try:
        with open(conf_path, "r", encoding="utf-8") as f:
            content = f.read()
            match = re.search(r"options\s+linuwu[_-]sense\s+([^\n]+)", content)
            if match:
                return match.group(1).strip()
    except Exception as e:
        log.error(f"Error reading modprobe config: {e}")
    return ""


def set_modprobe_parameter(param: str, conf_path: str = MODPROBE_CONF) -> bool:
    """Set modprobe parameter for linuwu_sense driver."""
    try:
        os.makedirs(os.path.dirname(conf_path), exist_ok=True)
        content = f"# Generated by AcerSense\noptions linuwu_sense {param}\n"
        with open(conf_path, "w", encoding="utf-8") as f:
            f.write(content)
        log.info(f"Updated modprobe configuration with: {param}")
        return True
    except Exception as e:
        log.error(f"Failed to write modprobe configuration: {e}")
        return False


def remove_modprobe_parameter(conf_path: str = MODPROBE_CONF) -> bool:
    """Remove modprobe configuration file."""
    try:
        if os.path.exists(conf_path):
            os.remove(conf_path)
            log.info("Removed modprobe configuration")
        return True
    except Exception as e:
        log.error(f"Failed to remove modprobe configuration: {e}")
        return False


def get_restart_attempts(file_path: str = RESTART_FILE) -> int:
    """Get the current count of driver restart attempts."""
    try:
        if os.path.exists(file_path):
            with open(file_path, "r", encoding="utf-8") as f:
                return int(f.read().strip())
    except Exception as e:
        log.warning(f"Failed to read restart attempts: {e}")
    return 0


def increment_restart_attempts(file_path: str = RESTART_FILE) -> int:
    """Increment and return driver restart counter."""
    try:
        os.makedirs(os.path.dirname(file_path), exist_ok=True)
        count = get_restart_attempts(file_path) + 1
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(str(count))
        return count
    except Exception as e:
        log.error(f"Failed to write restart attempts: {e}")
        return 0


def reset_restart_attempts(file_path: str = RESTART_FILE) -> None:
    """Reset driver restart attempts counter."""
    try:
        if os.path.exists(file_path):
            os.remove(file_path)
    except Exception as e:
        log.warning(f"Failed to reset restart attempts: {e}")
